Lib3MF4EOSHandle loadLib3MF4EOSLibrary (const char * pFileName)
{
	Lib3MF4EOSResult nResult;
	sLib3MF4EOSDynamicWrapperTable * pWrapperTable = (sLib3MF4EOSDynamicWrapperTable *) malloc (sizeof (sLib3MF4EOSDynamicWrapperTable));
	if (pWrapperTable != NULL) {
		nResult = InitLib3MF4EOSWrapperTable (pWrapperTable);
		if (nResult != LIB3MF4EOS_SUCCESS) {
			free (pWrapperTable);
			return 0;
		}

		nResult = LoadLib3MF4EOSWrapperTable (pWrapperTable, pFileName);
		if (nResult != LIB3MF4EOS_SUCCESS) {
			free (pWrapperTable);
			return 0;
		}

		return (Lib3MF4EOSHandle) pWrapperTable;
	}
}

