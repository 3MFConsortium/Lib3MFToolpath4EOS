	protected void checkError(Base instance, int errorCode) throws Lib3MF4EOSException {
		if (instance != null && instance.mWrapper != this) {
			throw new Lib3MF4EOSException(Lib3MF4EOSException.LIB3MF4EOS_ERROR_INVALIDCAST, "invalid wrapper call");
		}
		if (errorCode != Lib3MF4EOSException.LIB3MF4EOS_SUCCESS) {
			if (instance != null) {
				GetLastErrorResult result = getLastError(instance);
				throw new Lib3MF4EOSException(errorCode, result.ErrorMessage);
			} else {
				throw new Lib3MF4EOSException(errorCode, "");
			}
		}
	}

