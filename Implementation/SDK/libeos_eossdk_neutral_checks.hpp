#define LIBEOS_CHECK_NEUTRAL_SCALAR(NS, NAME) \
	static_assert((sizeof(Lib3MF4EOS::Impl::NAME) == sizeof(Lib3MF4EOS::Impl::NS::NAME)) && (std::is_signed<Lib3MF4EOS::Impl::NAME>::value == std::is_signed<Lib3MF4EOS::Impl::NS::NAME>::value) && (std::is_floating_point<Lib3MF4EOS::Impl::NAME>::value == std::is_floating_point<Lib3MF4EOS::Impl::NS::NAME>::value), "neutral scalar differs from " #NS ": " #NAME);

#define LIBEOS_CHECK_NEUTRAL_ENUM(NS, NAME) \
	static_assert((int)Lib3MF4EOS::Impl::NAME == (int)Lib3MF4EOS::Impl::NS::NAME, "neutral enum value differs from " #NS ": " #NAME);

#define LIBEOS_CHECK_NEUTRAL_ENUMSIZE(NS, NAME) \
	static_assert(sizeof(Lib3MF4EOS::Impl::NAME) == sizeof(Lib3MF4EOS::Impl::NS::NAME), "neutral enum size differs from " #NS ": " #NAME);

